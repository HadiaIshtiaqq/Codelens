"""One-line, plain-English narration for every trace step.

Static meaning comes from the line's syntax tree (parsed, never executed, so it
is safe in the API process); concrete values come from the recorded trace. A
`line` event fires *before* its line runs, so results are read from the next
event in the same frame. Nothing here is generated by a model.
"""

import ast
from typing import Any, Optional

MAX_EXPR = 40
MAX_VALUE = 30
MAX_NOTE = 160

_OPS = {
    ast.Add: ("Adds", "to"), ast.Sub: ("Subtracts", "from"), ast.Mult: ("Multiplies", "by"),
    ast.Div: ("Divides", "by"), ast.FloorDiv: ("Floor-divides", "by"), ast.Mod: ("Takes the remainder of", "by"),
    ast.Pow: ("Raises", "to the power"),
}
_METHODS = {
    "append": "Appends {arg} to {obj}", "extend": "Extends {obj} with {arg}", "insert": "Inserts into {obj}",
    "pop": "Removes an item from {obj}", "remove": "Removes {arg} from {obj}", "sort": "Sorts {obj} in place",
    "reverse": "Reverses {obj} in place", "clear": "Empties {obj}", "update": "Updates {obj} with {arg}",
    "add": "Adds {arg} to the set {obj}", "discard": "Discards {arg} from {obj}", "get": "Looks up {arg} in {obj}",
}


def _src(node: ast.AST) -> str:
    try:
        text = ast.unparse(node)
    except Exception:  # noqa: BLE001
        return "…"
    return text if len(text) <= MAX_EXPR else text[: MAX_EXPR - 1] + "…"


def _val(text: Optional[str]) -> str:
    if text is None:
        return "?"
    return text if len(text) <= MAX_VALUE else text[: MAX_VALUE - 1] + "…"


def _clip(text: str) -> str:
    return text if len(text) <= MAX_NOTE else text[: MAX_NOTE - 1] + "…"


def _statements_by_line(tree: ast.AST) -> dict[int, ast.stmt]:
    """Innermost statement that *starts* on each line."""
    by_line: dict[int, ast.stmt] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.stmt):
            current = by_line.get(node.lineno)
            if current is None or (node.col_offset, -node.end_lineno) > (current.col_offset, -current.end_lineno):
                by_line[node.lineno] = node
    return by_line


def _target_names(target: ast.AST) -> list[str]:
    if isinstance(target, ast.Name):
        return [target.id]
    if isinstance(target, (ast.Tuple, ast.List)):
        return [n for elt in target.elts for n in _target_names(elt)]
    if isinstance(target, ast.Starred):
        return _target_names(target.value)
    return []


def _call_name(call: ast.Call) -> str:
    return _src(call.func)


def _body_span(stmts: list[ast.stmt]) -> tuple[int, int]:
    return (stmts[0].lineno, max(s.end_lineno or s.lineno for s in stmts)) if stmts else (0, -1)


_COMPREHENSIONS = {ast.ListComp: "list", ast.SetComp: "set", ast.DictComp: "dict", ast.GeneratorExp: "generator"}


def _describe_value(value: ast.AST) -> Optional[str]:
    """Plain-English phrase for interesting right-hand sides, or None."""
    for kind, label in _COMPREHENSIONS.items():
        if isinstance(value, kind):
            gen = value.generators[0]
            cond = f" where {_src(gen.ifs[0])}" if gen.ifs else ""
            return f"builds a {label} from each {_src(gen.target)} in {_src(gen.iter)}{cond}"
    if isinstance(value, ast.Lambda):
        args = ", ".join(a.arg for a in value.args.args)
        return f"creates a small unnamed function of ({args}) that returns {_src(value.body)}"
    if isinstance(value, ast.IfExp):
        return f"picks {_src(value.body)} if {_src(value.test)}, otherwise {_src(value.orelse)}"
    if isinstance(value, ast.Call) and isinstance(value.func, ast.Name) and value.func.id == "input":
        return "asks the user for a line of input"
    return None


def _static(node: ast.stmt) -> str:
    """What a statement does, without runtime values (used for the 'explain every line' view)."""
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        args = ", ".join(a.arg for a in node.args.args)
        return f"Defines function {node.name}({args}); its body runs only when it is called"
    if isinstance(node, ast.ClassDef):
        return f"Defines class {node.name}, a blueprint for objects"
    if isinstance(node, ast.Assign):
        targets = " = ".join(_src(t) for t in node.targets)
        phrase = _describe_value(node.value)
        if phrase:
            return f"Sets {targets}: {phrase}"
        if isinstance(node.value, ast.Call):
            return f"Calls {_call_name(node.value)}(…) and stores the result in {targets}"
        if len(node.targets) == 1 and isinstance(node.targets[0], ast.Tuple) and isinstance(node.value, ast.Tuple):
            return f"Assigns {targets} all at once (e.g. a swap)"
        return f"Sets {targets} to {_src(node.value)}"
    if isinstance(node, ast.AnnAssign):
        return f"Declares {_src(node.target)} as {_src(node.annotation)}" + (f" = {_src(node.value)}" if node.value else "")
    if isinstance(node, ast.AugAssign):
        verb, prep = _OPS.get(type(node.op), ("Updates", "with"))
        if isinstance(node.op, (ast.Add, ast.Sub)):
            return f"{verb} {_src(node.value)} {prep} {_src(node.target)}"
        return f"{verb} {_src(node.target)} {prep} {_src(node.value)}"
    if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
        call = node.value
        if isinstance(call.func, ast.Name) and call.func.id == "print":
            return "Prints " + (", ".join(_src(a) for a in call.args) or "an empty line")
        if isinstance(call.func, ast.Attribute) and call.func.attr in _METHODS:
            arg = _src(call.args[0]) if call.args else ""
            return _METHODS[call.func.attr].format(obj=_src(call.func.value), arg=arg)
        return f"Calls {_call_name(call)}(…)"
    if isinstance(node, ast.If):
        test = node.test
        if (isinstance(test, ast.Compare) and isinstance(test.left, ast.Name) and test.left.id == "__name__"):
            return "Checks whether this file is being run directly (not imported)"
        return f"Checks if {_src(test)}"
    if isinstance(node, ast.For):
        return f"Loop: {_src(node.target)} takes each value from {_src(node.iter)}"
    if isinstance(node, ast.While):
        return f"Loop: repeats while {_src(node.test)}"
    if isinstance(node, ast.Return):
        if node.value is not None and (phrase := _describe_value(node.value)):
            return f"Returns the result: {phrase}"
        return f"Returns {_src(node.value)}" if node.value else "Returns None"
    if isinstance(node, (ast.Import, ast.ImportFrom)):
        return "Imports " + ", ".join(a.name for a in node.names)
    if isinstance(node, ast.Pass):
        return "Does nothing (placeholder)"
    if isinstance(node, ast.Break):
        return "Leaves the loop early"
    if isinstance(node, ast.Continue):
        return "Skips to the next loop round"
    if isinstance(node, ast.Raise):
        return f"Raises an error on purpose: {_src(node.exc)}" if node.exc else "Re-raises the current error"
    if isinstance(node, ast.Assert):
        return f"Checks that {_src(node.test)} is true, or stops with AssertionError"
    if isinstance(node, ast.Try):
        return "Starts a try block: errors inside can be caught"
    if isinstance(node, ast.With):
        return "Opens a with block that cleans up automatically"
    if isinstance(node, ast.Delete):
        return "Deletes " + ", ".join(_src(t) for t in node.targets)
    if isinstance(node, (ast.Global, ast.Nonlocal)):
        return "Uses the outer variable(s) " + ", ".join(node.names)
    if isinstance(node, ast.Expr):
        return f"Evaluates {_src(node.value)}"
    return "Runs this line"


def line_notes(source: str) -> dict[int, str]:
    """Static one-line explanation for every line that starts a statement."""
    try:
        tree = ast.parse(source)
    except (SyntaxError, ValueError):
        return {}
    return {line: _clip(_static(node)) for line, node in sorted(_statements_by_line(tree).items())}


class _Narrator:
    def __init__(self, sources: dict[str, str], events: list[dict[str, Any]]):
        self.events = events
        self.stmts_by_file: dict[str, dict[int, ast.stmt]] = {}
        self.class_lines: dict[tuple[str, int], str] = {}
        for name, text in sources.items():
            try:
                tree = ast.parse(text)
            except (SyntaxError, ValueError):
                continue
            self.stmts_by_file[name] = _statements_by_line(tree)
            # A class body runs as its own frame named after the class; narrate it as building the class.
            for n in ast.walk(tree):
                if isinstance(n, ast.ClassDef):
                    self.class_lines[(name, n.lineno)] = n.name
        self.building: list[str] = []
        self.crashed_once = False

    def _after(self, k: int) -> Optional[dict[str, Any]]:
        """Next event in the same frame (state after line k ran)."""
        ev = self.events[k]
        for j in range(k + 1, len(self.events)):
            nxt = self.events[j]
            if nxt["event"] in ("stdout", "exit"):
                continue
            if nxt["stack_depth"] < ev["stack_depth"]:
                return None
            if nxt["stack_depth"] == ev["stack_depth"] and nxt["function"] == ev["function"]:
                # Python 3.12+ runs comprehensions inside the same frame, repeating the line's event:
                # the line has finished only when the next event is somewhere else.
                if nxt["event"] == "line" and nxt["line"] == ev["line"] and ev["event"] == "line":
                    continue
                return nxt
        return None

    def _called(self, k: int) -> Optional[str]:
        nxt = self.events[k + 1] if k + 1 < len(self.events) else None
        if nxt and nxt["event"] == "call" and nxt["stack_depth"] > self.events[k]["stack_depth"]:
            return nxt["function"]
        return None

    def narrate(self, k: int) -> str:
        ev = self.events[k]
        kind = ev["event"]
        in_main = ev.get("file", "main.py") == "main.py"
        if kind == "call":
            if ev["function"] == "<module>":
                if in_main:
                    return "▶ The program starts running from the top"
                return f"Imports {ev['file']}: runs it from the top once"
            if self.class_lines.get((ev.get("file", "main.py"), ev["line"])) == ev["function"]:
                self.building.append(ev["function"])
                return f"Starts building class {ev['function']}: collects its methods"
            args = [f"{n} = {_val(ev['locals'].get(n))}" for n in ev.get("arg_names", []) if n in ev["locals"]]
            where = f" in {ev['file']}" if ev.get("file", "main.py") != "main.py" else ""
            return f"Enters {ev['function']}(){where}" + (f" with {', '.join(args)}" if args else "")
        if kind == "return":
            if ev["function"] == "<module>":
                return "Reaches the end of the program" if in_main else f"Finished importing {ev['file']}"
            if self.building and self.building[-1] == ev["function"]:
                self.building.pop()
                return f"Class {ev['function']} is ready to use"
            return f"{ev['function']}() is done and hands back {_val(ev.get('return_value'))}"
        if kind == "exception":
            exc = ev["exception"]
            if not self.crashed_once:
                self.crashed_once = True
                return f"💥 Crash! {exc['type']}: {exc['message']}"
            return f"The {exc['type']} escapes into {ev['function']}"
        if kind == "stdout":
            return f"Prints {ev['stdout_chunk'].rstrip(chr(10))!r} to the screen"
        if kind == "exit":
            code = ev.get("exit_code")
            return "🏁 The program finished successfully" if code == 0 else f"The program stopped with exit code {code}"
        return self._line(k)

    def _line(self, k: int) -> str:
        ev = self.events[k]
        node = self.stmts_by_file.get(ev.get("file", "main.py"), {}).get(ev["line"])
        if node is None:
            return f"Runs line {ev['line']}"
        after = self._after(k)
        after_locals = after["locals"] if after else {}
        note = _static(node)
        called = self._called(k)

        def now(names: list[str]) -> str:
            shown = [f"{n} = {_val(after_locals[n])}" for n in names if n in after_locals]
            return f" → {', '.join(shown)}" if shown else ""

        if isinstance(node, ast.Assign):
            names = [n for t in node.targets for n in _target_names(t)]
            if _describe_value(node.value):
                pass  # keep the richer static wording (comprehension, lambda, input(), ...)
            elif isinstance(node.value, ast.Call):
                note = f"Calls {_call_name(node.value)}(…) and stores the result in {', '.join(names) or _src(node.targets[0])}"
            elif names and len(names) == 1 and not isinstance(node.targets[0], (ast.Tuple, ast.List)):
                note = f"Sets {names[0]} to {_src(node.value)}"
            note += now(names)
        elif isinstance(node, (ast.AugAssign, ast.AnnAssign)):
            note += now(_target_names(node.target))
        elif isinstance(node, (ast.If, ast.While)):
            if after and after["event"] in ("line", "return"):
                start, end = _body_span(node.body)
                taken = after["event"] == "line" and start <= after["line"] <= end
                note += " → True" if taken else (" → False, so the loop ends" if isinstance(node, ast.While) else " → False")
        elif isinstance(node, ast.For):
            if after and after["event"] in ("line", "return"):
                start, end = _body_span(node.body)
                if after["event"] == "line" and start <= after["line"] <= end:
                    note = f"Loop: {_src(node.target)} takes the next value from {_src(node.iter)}" + now(_target_names(node.target))
                else:
                    note = f"Loop over {_src(node.iter)} is finished: no values left"
        elif isinstance(node, ast.Return):
            ret = self.events[k + 1] if k + 1 < len(self.events) else None
            if ret and ret["event"] == "return" and not called:
                note += f" = {_val(ret.get('return_value'))}"
        # A class statement runs its body as a frame named after the class; that is not a call.
        if called and not note.startswith("Calls") and not isinstance(node, ast.ClassDef):
            note += f" (calls {called}())"
        return note


def annotate(sources: "dict[str, str] | str", events: list[dict[str, Any]]) -> None:
    """Add a `narration` string to every event, in place. `sources` maps file name -> code."""
    if isinstance(sources, str):
        sources = {"main.py": sources}
    narrator = _Narrator(sources, events)
    for k, ev in enumerate(events):
        try:
            ev["narration"] = _clip(narrator.narrate(k))
        except Exception:  # noqa: BLE001 - narration must never break a run
            ev["narration"] = f"Runs line {ev.get('line', '?')}"
