// Generates src/theme.css: Tailwind's palettes as CSS variables, plus a light theme.
//
// The app is designed dark. Light mode flips every palette (50 <-> 950, 100 <-> 900, …), so
// "dark surface, light text" becomes "light surface, dark text" everywhere without touching
// components. White and black swap roles too. Run after changing palettes: node scripts/gen-theme.mjs
import { writeFileSync } from 'node:fs';
import colors from 'tailwindcss/colors.js';
import { PALETTES, SHADES } from './gen-theme-palettes.mjs';


const rgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
};

const dark = [];
const light = [];
for (const name of PALETTES) {
  SHADES.forEach((shade, i) => {
    dark.push(`  --c-${name}-${shade}: ${rgb(colors[name][shade])};`);
    // Flip the scale around 500, which stays put (buttons and accents keep their colour; 400 text becomes 600, readable on white).
    const flipped = SHADES[SHADES.length - 1 - i];
    const keep = shade === '500';
    light.push(`  --c-${name}-${shade}: ${rgb(colors[name][keep ? shade : flipped])};`);
  });
}
dark.push('  --c-white: 255 255 255;', '  --c-black: 0 0 0;');
light.push(`  --c-white: ${rgb(colors.slate['900'])};`, '  --c-black: 255 255 255;');

const css = `/* Generated by scripts/gen-theme.mjs. Do not edit by hand. */
:root {
${dark.join('\n')}
}
:root.light {
${light.join('\n')}
}
`;
writeFileSync(new URL('../src/theme.css', import.meta.url), css);
console.log(`wrote src/theme.css (${PALETTES.length} palettes)`);
